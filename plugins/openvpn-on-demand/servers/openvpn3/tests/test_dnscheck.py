def test_read_resolv_conf_follows_relative_symlink(tmp_path, monkeypatch):
    (tmp_path / "run/systemd/resolve").mkdir(parents=True)
    (tmp_path / "run/systemd/resolve/stub-resolv.conf").write_text(STUB_RESOLV)
    (tmp_path / "etc").mkdir()
    (tmp_path / "etc/resolv.conf").symlink_to("../run/systemd/resolve/stub-resolv.conf")
    monkeypatch.setattr(dnscheck, "RESOLV_CONF", tmp_path / "etc/resolv.conf")
    got = dnscheck.read_resolv_conf()
    assert (got.owner, got.nameservers, got.symlink, got.is_stub) == ("systemd-resolved stub", ["127.0.0.53"], True, True)


def test_read_resolv_conf_dangling_symlink_is_not_a_stub(tmp_path, monkeypatch):
    (tmp_path / "resolv.conf").symlink_to(tmp_path / "missing/run/systemd/resolve/stub-resolv.conf")
    monkeypatch.setattr(dnscheck, "RESOLV_CONF", tmp_path / "resolv.conf")
    got = dnscheck.read_resolv_conf()
    assert got.owner == "systemd-resolved stub"
    assert not got.is_stub


