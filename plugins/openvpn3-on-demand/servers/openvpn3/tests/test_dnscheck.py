def _decide(
    *,
    resolv: ResolvConf = TAILSCALE,
    hosts_line: str | None = HOSTS_LINE,
    nss_resolve: bool = False,
    links: dict[str, list[str]] | None = TUN_LINKS,
    host: str | None = None,
    resolved: Lookup | None = None,
    nss: Lookup | None = None,
    pins: list[str] | None = None,
    connected: bool = False,
) -> dnscheck.Report:
    """This host's 2026-09-25 state (Tailscale owns resolv.conf, no nss-resolve, tunnel up) unless overridden."""
    return dnscheck.decide(
        resolv=resolv, hosts_line=hosts_line, nss_resolve=nss_resolve, links=links, host=host, connected=connected, resolved=resolved, nss=nss, pins=pins, netcfg="true"
    )


def _probe(resolved: Lookup, nss: Lookup, pins: list[str] | None = None, resolv: ResolvConf = TAILSCALE) -> dnscheck.Report:
    return _decide(host=MEMORYDB, resolved=resolved, nss=nss, pins=pins, resolv=resolv)


def _fix_text(report):
    return "\n".join(report.fix)


def test_filtered_answer_is_fail_with_the_tailscale_fix():
    # The 2026-09-25 incident: resolved gets the private IP via tun0, programs get 0.0.0.0 from quad-100/NextDNS.
    report = _probe(Lookup(["10.0.12.34"], links=["tun0"]), Lookup(["0.0.0.0"]))
    assert report.verdict == FAIL
    assert "Programs get 0.0.0.0" in report.reason
    assert "filtered" in report.reason
    fix = _fix_text(report)
    assert "sudo ln -sfn ../run/systemd/resolve/stub-resolv.conf /etc/resolv.conf" in fix
    assert "sudo systemctl restart tailscaled" in fix
    assert "sudo apt install libnss-resolve" in fix


