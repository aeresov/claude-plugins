@pytest.fixture
def fake_host(tmp_path, monkeypatch):
    """Point every file at tmp_path fixtures and route subprocess calls through a table; returns (files, calls, answers)."""
    files = {
        "RESOLV_CONF": tmp_path / "resolv.conf",
        "NSSWITCH_CONF": tmp_path / "nsswitch.conf",
        "HOSTS_FILE": tmp_path / "hosts",
        "NETCFG_JSON": tmp_path / "netcfg.json",
    }
    files["RESOLV_CONF"].write_text(TAILSCALE_RESOLV)
    files["NSSWITCH_CONF"].write_text(f"hosts:          {HOSTS_LINE}\n")
    files["HOSTS_FILE"].write_text("127.0.0.1 localhost\n")
    files["NETCFG_JSON"].write_text('{ "systemd_resolved" : true }\n')
    for name, path in files.items():
        monkeypatch.setattr(dnscheck, name, path)
    (tmp_path / "run-resolve").mkdir()
    monkeypatch.setattr(dnscheck, "RESOLVED_RUN_DIR", tmp_path / "run-resolve")
    monkeypatch.setattr(dnscheck, "nss_resolve_installed", lambda: False)

    calls: list[list[str]] = []
    answers: dict[str, object] = {
        "resolvectl domain": (0, RESOLVECTL_DOMAIN, ""),
        "resolvectl query": (0, f"{MEMORYDB}: 10.0.12.34 -- link: tun0\n", ""),
        "getent ahosts": (0, f"0.0.0.0 STREAM {MEMORYDB}\n0.0.0.0 DGRAM\n", ""),
    }

    def fake_run(argv):
        calls.append(argv)
        answer = answers[" ".join(argv[:2])]
        if isinstance(answer, BaseException):
            raise answer
        rc, out, err = answer  # ty: ignore[not-iterable]
        return subprocess.CompletedProcess(argv, rc, out, err)

    monkeypatch.setattr(dnscheck, "_run", fake_run)
    return files, calls, answers


